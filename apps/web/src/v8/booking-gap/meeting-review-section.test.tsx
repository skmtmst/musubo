// @vitest-environment happy-dom
import React from 'react'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
const net = vi.hoisted(() => ({ meetingReviews: vi.fn(), resolveMeetingReview: vi.fn(), meetingStatus: vi.fn(), retryMeeting: vi.fn(), setBookingUrl: vi.fn(), role: vi.fn() }))
vi.mock('@/lib/api/helpers/gap1', () => ({ bookingCalendarApi: net }))
vi.mock('@/lib/staff-role', () => ({ useStaffRole: net.role, canAdministerRole: (role: string) => role === 'admin' || role === 'owner' }))
const { MeetingReviewSection } = await import('./meeting-review-section')
const { ApiError } = await import('@/lib/api')
afterEach(() => { cleanup(); vi.resetAllMocks() })
it('確実な失敗だけ再発行でき、結果不明なら操作を隠す', async () => {
  net.role.mockReturnValue('owner')
  net.meetingReviews.mockResolvedValue({ data: { items: [] } })
  net.meetingStatus.mockResolvedValue({ data: { state: 'failed', provider: 'zoom' } })
  net.retryMeeting.mockResolvedValue({ data: { outcome: 'unknown' } })
  render(<MeetingReviewSection accountId="account" bookingId="booking" canOperate />)
  fireEvent.click(await screen.findByRole('button', { name: 'もう一度発行する' }))
  await waitFor(() => expect(net.retryMeeting).toHaveBeenCalledWith('account', 'booking', expect.any(String)))
  expect(await screen.findAllByText('相手のサービスで確かめてください。')).not.toHaveLength(0)
  expect(screen.queryByRole('button', { name: 'もう一度発行する' })).toBeNull()
})
it.each(['unknown','teams'] as const)('%s では再発行を出さない', async state => {
  net.role.mockReturnValue('owner')
  net.meetingReviews.mockResolvedValue({ data: { items: [] } })
  net.meetingStatus.mockResolvedValue({ data: state === 'teams' ? { state: 'failed', provider: 'teams' } : { state: 'unknown', provider: 'zoom' } })
  render(<MeetingReviewSection accountId="account" bookingId="booking" canOperate />)
  await screen.findByText(state === 'teams' ? 'Teams の会議は相手のサービスで確認してください。' : '相手のサービスで確かめてください。')
  expect(screen.queryByRole('button', { name: 'もう一度発行する' })).toBeNull()
})
it('失敗した会議に手入力の URL を版付きで保存する', async () => {
  net.role.mockReturnValue('owner')
  net.meetingReviews.mockResolvedValue({ data: { items: [] } })
  net.meetingStatus.mockResolvedValue({ data: { state: 'failed', provider: 'zoom', version: 7 } })
  net.setBookingUrl.mockResolvedValue({ data: { url: 'https://zoom.us/j/1', version: 8, source: 'manual' } })
  render(<MeetingReviewSection accountId="account" bookingId="booking" canOperate />)
  const input = await screen.findByRole('textbox', { name: '会議の URL（https://）' })
  const save = screen.getByRole('button', { name: 'URL を保存' }) as HTMLButtonElement
  expect(save.disabled).toBe(true)
  expect(screen.getByText('URL を入力してください。')).toBeTruthy()
  expect(input.parentElement?.contains(save)).toBe(true)
  fireEvent.change(input, { target: { value: 'https://zoom.us/j/1' } })
  expect(save.disabled).toBe(false)
  fireEvent.click(screen.getByRole('button', { name: 'URL を保存' }))
  await waitFor(() => expect(net.setBookingUrl).toHaveBeenCalledWith('account', 'booking', { action: 'set_manual', url: 'https://zoom.us/j/1', expectedVersion: 7 }))
})
it('再発行の通信が途切れたら再発行も手入力も出さず確認を求める', async () => {
  net.role.mockReturnValue('owner')
  net.meetingReviews.mockResolvedValue({ data: { items: [] } })
  net.meetingStatus.mockResolvedValue({ data: { state: 'failed', provider: 'zoom', version: 7 } })
  net.retryMeeting.mockRejectedValue(new Error('timeout'))
  render(<MeetingReviewSection accountId="account" bookingId="booking" canOperate />)
  fireEvent.click(await screen.findByRole('button', { name: 'もう一度発行する' }))
  expect(await screen.findByText('相手のサービスで確かめてください。')).toBeTruthy()
  expect(screen.queryByRole('button', { name: 'もう一度発行する' })).toBeNull()
  expect(screen.queryByRole('button', { name: 'URL を保存' })).toBeNull()
})
it('元の会議は相手先で削除したと確認してから記録する', async () => {
  net.role.mockReturnValue('admin')
  net.meetingReviews.mockResolvedValue({ data: { items: [{ id: 'link', provider: 'zoom', staff_name: '担当', starts_at: null, ends_at: null }] } })
  net.resolveMeetingReview.mockResolvedValue({ data: { resolved: true } })
  render(<MeetingReviewSection accountId="account" bookingId="booking" canOperate />)
  fireEvent.click(await screen.findByRole('button', { name: '相手先で削除した' }))
  expect(net.resolveMeetingReview).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: '削除したことを記録' }))
  await waitFor(() => expect(net.resolveMeetingReview).toHaveBeenCalledWith('account', 'booking', 'link'))
})
it('閲覧のみでは記録の操作を出さない', async () => {
  net.role.mockReturnValue('admin')
  net.meetingReviews.mockResolvedValue({ data: { items: [{ id: 'link', provider: 'zoom', staff_name: '担当', starts_at: null, ends_at: null }] } })
  render(<MeetingReviewSection accountId="account" bookingId="booking" canOperate={false} />)
  await screen.findByText(/Zoom・担当/)
  expect(screen.queryByRole('button', { name: '相手先で削除した' })).toBeNull()
})
it('ほかの操作で対象が解決済みなら一覧を読み直す', async () => {
  net.role.mockReturnValue('owner')
  net.meetingReviews.mockResolvedValueOnce({ data: { items: [{ id: 'link', provider: 'zoom', staff_name: '担当', starts_at: null, ends_at: null }] } }).mockResolvedValueOnce({ data: { items: [] } })
  net.resolveMeetingReview.mockRejectedValue(new ApiError(404, 'not found'))
  render(<MeetingReviewSection accountId="account" bookingId="booking" canOperate />)
  fireEvent.click(await screen.findByRole('button', { name: '相手先で削除した' }))
  fireEvent.click(screen.getByRole('button', { name: '削除したことを記録' }))
  expect(await screen.findByText('会議の状態が変わったため、一覧を更新しました。')).toBeTruthy()
  expect(screen.queryByRole('button', { name: '相手先で削除した' })).toBeNull()
})

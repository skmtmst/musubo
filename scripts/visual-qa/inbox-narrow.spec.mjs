import { test, expect } from '@playwright/test'
import { routeLocalApi } from './local-api.mjs'

const base = process.env.VISUAL_QA_BASE ?? 'http://localhost:3101'
test.beforeEach(routeLocalApi)

for (const width of [1024, 1152]) {
  test(`${width}px では一覧と会話を切り替え、選んだ相手を保つ`, async ({ page }) => {
    const insertionErrors = []
    page.on('console', message => { if (message.text().includes('useInsertionEffect must not schedule updates')) insertionErrors.push(message.text()) })
    await page.setViewportSize({ width, height: 900 })
    await page.addInitScript(() => {
      localStorage.setItem('lh_selected_account', 'visual-qa-account')
      localStorage.setItem('lh_csrf', 'visual-qa-csrf')
      sessionStorage.setItem('lh_visual_qa_capture', '1')
      sessionStorage.setItem('lh_auth_selection_cleared', '1')
    })
    await page.goto(`${base}/chats`, { waitUntil: 'networkidle' })
    const list = page.locator('[data-inbox-v4="conversation-list"]')
    const talk = page.locator('[data-inbox-v4="talk-pane"]')
    const info = page.locator('[data-inbox-v4="customer-panel"]')
    const row = page.getByRole('button', { name: 'Kyohei Yamamoto' })
    await expect(row).toBeVisible()
    await expect(talk).toBeHidden()
    await expect(info).toHaveCount(0)
    const frame = page.locator('[data-template-region="body"]')
    expect(Math.abs((await list.boundingBox()).width - (await frame.boundingBox()).width)).toBeLessThan(2)
    await row.click()
    await expect(list).toBeHidden()
    await expect(talk).toBeVisible()
    await expect(info).toBeVisible()
    const sent = talk.locator('[role="article"]').filter({ has: page.locator('[data-inbox-v6="correct-message"]') }).first()
    await expect(sent).toBeVisible()
    const bubble = sent.locator('[class*="bubbleOut"]')
    const beforeHover = await bubble.boundingBox()
    await sent.hover()
    const quote = sent.locator('[data-inbox-v6="quote-reply"]')
    const correct = sent.locator('[data-inbox-v6="correct-message"]')
    await expect(quote).toBeVisible()
    await expect(correct).toBeVisible()
    const bounds = await sent.boundingBox(), quoteBox = await quote.boundingBox(), correctBox = await correct.boundingBox()
    const bubbleBox = await bubble.boundingBox()
    const statusBox = await sent.getByRole('status').boundingBox()
    expect(quoteBox.x).toBeGreaterThanOrEqual(bounds.x - 1)
    expect(correctBox.x + correctBox.width).toBeLessThanOrEqual(bounds.x + bounds.width + 1)
    expect(quoteBox.x + quoteBox.width).toBeLessThanOrEqual(correctBox.x + 1)
    expect(correctBox.x + correctBox.width).toBeLessThanOrEqual(statusBox.x + 1)
    expect(Math.abs(bubbleBox.x - (statusBox.x + statusBox.width) - 8)).toBeLessThan(2)
    expect(Math.abs(statusBox.y + statusBox.height - bubbleBox.y - bubbleBox.height)).toBeLessThan(2)
    expect(Math.abs(beforeHover.width - bubbleBox.width)).toBeLessThan(1)
    expect(Math.abs(beforeHover.height - bubbleBox.height)).toBeLessThan(1)
    const inputBox = talk.locator('[data-input-field]:has([data-insert-field])')
    const sendButton = talk.getByRole('button', { name: '送信する' })
    const inputRect = await inputBox.boundingBox(), sendRect = await sendButton.boundingBox()
    expect(sendRect.x).toBeGreaterThanOrEqual(inputRect.x)
    expect(sendRect.x + sendRect.width).toBeLessThanOrEqual(inputRect.x + inputRect.width + 1)
    expect(sendRect.y + sendRect.height).toBeLessThanOrEqual(inputRect.y + inputRect.height + 1)
    await expect(page.getByRole('button', { name: '‹ 一覧を表示' })).toBeFocused()
    const talkBox = await talk.boundingBox(), infoBox = await info.boundingBox()
    expect(Math.abs(talkBox.x + talkBox.width - infoBox.x)).toBeLessThan(2)
    expect(infoBox.x + infoBox.width).toBeLessThanOrEqual(width)
    const composer = page.getByRole('textbox', { name: 'メッセージを入力' })
    await composer.fill('入力途中の返信')
    await page.getByRole('button', { name: '‹ 一覧を表示' }).click()
    await expect(list).toBeVisible()
    await expect(talk).toBeHidden()
    await expect(row).toHaveAttribute('aria-current', 'true')
    await expect(row).toBeFocused()
    await row.click()
    await expect(composer).toHaveText('入力途中の返信')
    await page.setViewportSize({ width: 1440, height: 900 })
    await expect(list).toBeVisible()
    await expect(talk).toBeVisible()
    await expect(info).toBeVisible()
    expect(insertionErrors).toEqual([])
    await expect(row).toHaveAttribute('aria-current', 'true')
    await expect(composer).toHaveText('入力途中の返信')
    await page.setViewportSize({ width, height: 900 })
    await expect(list).toBeHidden()
    await expect(talk).toBeVisible()
    await expect(info).toBeVisible()
  })
}

for (const width of [1024, 1152]) {
  test(`${width}px では不正な会話への案内から一覧へ戻れる`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.addInitScript(() => {
      localStorage.setItem('lh_selected_account', 'visual-qa-account')
      localStorage.setItem('lh_csrf', 'visual-qa-csrf')
      sessionStorage.setItem('lh_visual_qa_capture', '1')
      sessionStorage.setItem('lh_auth_selection_cleared', '1')
    })
    await page.goto(`${base}/chats?friend=bad%2Fid`, { waitUntil: 'networkidle' })
    await expect(page.getByText('会話を開けませんでした', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '‹ 一覧を表示' }).click()
    await expect(page.getByRole('button', { name: 'Kyohei Yamamoto' })).toBeVisible()
    await expect(page.getByText('会話を開けませんでした', { exact: true })).toBeHidden()
  })
}
